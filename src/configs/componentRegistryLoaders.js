/**
 * Чем грузится реестр компонентов каждого типа проекта.
 *
 * Вынесено из конфигов типов, хотя объявлялось в них. Вопрос «есть ли у этого
 * типа реестр» задают из стартового графа — нижняя навигация на каждой
 * отрисовке, владелец списка на каждой смене проекта, — и `componentRegistry`
 * отвечал на него, читая `PROJECTS`. То есть ради одной проверки на месте
 * приезжали три полных конфига: поля, словари, шаги формы, колонки выгрузки.
 * Разделение, которое там уже было сделано, не работало: модуль остался
 * дешёвым, а его импорт — нет.
 *
 * Обещание при этом сохранено: ответ по-прежнему выводится из объявления, а не
 * из сравнения с именем типа. Просто объявление теперь лежит здесь, и конфиг
 * типа берёт свой загрузчик отсюда же — источник один.
 */
export const COMPONENT_REGISTRY_LOADERS = {
  upstream: () => import("@/configs/upstream/data/componentBlock"),
  midstream: () => import("@/configs/midstream/data/componentBlock"),
  downstream: () => import("@/configs/downstream/data/componentBlock"),
};
