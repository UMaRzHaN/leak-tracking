import { COMPONENT_REGISTRY_LOADERS } from "./componentRegistryLoaders";

/**
 * Есть ли у типа проекта реестр компонентов — и у каких типов он есть.
 *
 * Отдельно от projectAdapter намеренно. Обе проверки синхронные и дешёвые, и
 * спрашивают их из стартового графа: нижняя навигация — на каждой отрисовке,
 * владелец списка реестра — на каждой смене проекта. Всё остальное в
 * projectAdapter описывает поля утечки и на холодном старте не нужно, а лежали
 * бы они вместе — приезжало бы вместе.
 *
 * Ответ выводится из самого объявления: тип, не объявивший загрузчик реестра,
 * реестра просто не имеет. Никаких сравнений с именем типа — это то же
 * обещание, что и в projectAdapter. Объявление живёт в
 * `componentRegistryLoaders`, оттуда же его берут и конфиги типов: раньше оно
 * стояло внутри `PROJECTS`, и дешёвая проверка тянула на первый экран все три
 * конфига целиком.
 */

/**
 * Без подстановки типа по умолчанию — намеренно.
 *
 * Раньше незнакомый тип и `null` уходили в `PROJECTS.midstream`, и ответом было
 * «нет» просто потому, что midstream реестра не вёл. Теперь его ведут все три
 * типа, и та же подстановка стала бы отвечать «да» на вопрос о проекте,
 * которого не существует, — раздел реестра появился бы в навигации у пустоты.
 * Незнакомый тип не ведёт реестра, и это ответ по существу, а не следствие
 * того, на какой тип пришлась подстановка.
 *
 * @param {{type?: string}|string} project
 * @returns {boolean}
 */
export function hasComponentRegistry(project) {
  const type = /** @type {{type?: string}} */ (project)?.type ?? project;
  return typeof COMPONENT_REGISTRY_LOADERS[type] === "function";
}

/**
 * Типы проектов, которые вообще ведут реестр компонентов.
 *
 * Нужен там, где реестр приезжает раньше проекта: архив инвентаризации не
 * несёт ни имени проекта, ни его типа — только карточки. Если реестр объявлен
 * ровно у одного типа, выбирать не из чего, и спрашивать человека не о чем;
 * если типов станет несколько, ответ перестанет быть однозначным сам, и
 * вызывающая сторона это увидит.
 *
 * @returns {string[]}
 */
export function componentRegistryProjectTypes() {
  return Object.keys(COMPONENT_REGISTRY_LOADERS).filter((type) =>
    hasComponentRegistry(type),
  );
}
