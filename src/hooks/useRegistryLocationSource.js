import { useComponentRegistryStore } from "@/features/componentRegistry/ComponentRegistryContext";

export { COMPONENT_REGISTRY_UPDATED } from "@/repositories/componentRegistrySignal";

/**
 * Компоненты — только затем, чтобы шапка считала папки по ним.
 *
 * Выбор места один на всё приложение, и на экране реестра он должен считать
 * то, что на этом экране лежит: иначе рядом с «Мессояхское УПГ» стоит число
 * утечек, а открывается папка с железом. Реестр читается по своему ключу и в
 * общий список записей не входит, поэтому шапке приходится смотреть в него
 * отдельно.
 *
 * Список берётся у провайдера, а не читается с диска: экран реестра держит
 * ровно этот же список, и раньше эти двое читали хранилище порознь — дважды
 * при открытии экрана и ещё раз с диска после каждой сохранённой карточки.
 *
 * Проект спрашивать не у кого и незачем: активный проект знает провайдер, и
 * два ответа на этот вопрос разошлись бы ровно в момент переключения.
 */
export function useRegistryLocationSource(active) {
  const { components } = useComponentRegistryStore({ active });
  // Пока реестр не открыт, шапка считает папки по утечкам, и карточки ей не
  // просто не нужны — они дали бы другое дерево.
  return active ? components : EMPTY;
}

const EMPTY = /** @type {any[]} */ (Object.freeze([]));
