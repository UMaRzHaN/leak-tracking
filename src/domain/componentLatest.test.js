import { describe, expect, it } from "vitest";
import { findLatestComponent } from "@/domain/componentRegistry";

/**
 * Какая карточка даёт подсказки в форме заведения.
 *
 * Форма подставляет призрачные подсказки из последней заведённой карточки:
 * обходчик идёт по одному узлу и заполняет соседние поля одинаково. Взять не ту
 * карточку — значит показать подсказки от произвольного оборудования, обычно
 * заполненного на треть.
 *
 * Дата в карточке приходит в трёх видах. Заведённая в приложении несёт ISO;
 * приехавшая из книги — либо число миллисекунд, если ячейка была настоящей
 * датой, либо текст «10.03.2026», если ячейка была текстом. Инвентаризация
 * кладёт в карточку то, что нашла в ячейке, и не приводит это к общему виду.
 */
const card = (id, date) => ({ id, component_uid: id, date });

const MARCH_10 = "2026-03-10T08:00:00.000Z";
const MARCH_25 = "2026-03-25T08:00:00.000Z";

describe("последняя заведённая карточка", () => {
  it("выбирается по дате, а не по месту в списке", () => {
    expect(
      findLatestComponent([card("поздняя", MARCH_25), card("ранняя", MARCH_10)])
        .id,
    ).toBe("поздняя");
  });

  it("читает точечную дату из книги как день, а не как месяц", () => {
    // `Date.parse("10.03.2026")` отвечает вторым октября, а «25.03.2026» —
    // вовсе ничем: числа больше двенадцати за месяц не сходят. После импорта
    // инвентаризации нечитаемыми оказывались почти все карточки разом, и выбор
    // сваливался на последнюю в массиве — ровно то, от чего уходили.
    expect(
      findLatestComponent([
        card("двадцать пятое", "25.03.2026"),
        card("десятое", "10.03.2026"),
      ]).id,
    ).toBe("двадцать пятое");
  });

  it("читает дату-число из ячейки настоящей датой", () => {
    // Поздняя стоит первой нарочно: пока даты были нечитаемы, выбор падал на
    // последнюю в массиве, и порядок «поздняя в конце» скрыл бы это.
    expect(
      findLatestComponent([
        card("поздняя", Date.parse(MARCH_25)),
        card("ранняя", Date.parse(MARCH_10)),
      ]).id,
    ).toBe("поздняя");
  });

  it("сводит вместе карточки из книги и заведённые в приложении", () => {
    expect(
      findLatestComponent([
        card("из книги", "25.03.2026"),
        card("из приложения", MARCH_10),
      ]).id,
    ).toBe("из книги");
  });

  it("карточка без читаемой даты годится, пока нет датированной", () => {
    expect(findLatestComponent([card("без даты", "")]).id).toBe("без даты");
    expect(
      findLatestComponent([card("без даты", ""), card("с датой", MARCH_10)]).id,
    ).toBe("с датой");
  });

  it("пустой реестр не даёт карточки", () => {
    expect(findLatestComponent([])).toBeNull();
    expect(findLatestComponent(null)).toBeNull();
  });
});
