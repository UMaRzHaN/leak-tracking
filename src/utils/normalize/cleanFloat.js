/**
 * Число без хвоста двоичной погрешности: `46.80000000000001` → `46.8`.
 *
 * Такие хвосты рождаются арифметикой — пересчётом из кельвинов, формулой в
 * чужой таблице — и приезжают в данные импортом. Показывать их нечестно:
 * человек видит «точность», которой у прибора нет. Пятнадцать значащих цифр —
 * предел точности самого числа, поэтому настоящие значения, включая
 * координаты, остаются как есть.
 *
 * @template T
 * @param {T} value
 * @returns {T}
 */
export function cleanFloat(value) {
  if (typeof value !== "number" || !Number.isFinite(value)) return value;
  return /** @type {T} */ (
    /** @type {unknown} */ (Number(value.toPrecision(15)))
  );
}
