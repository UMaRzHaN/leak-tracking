/**
 * Дата, набираемая руками, в формате ДД.ММ.ГГГГ.
 *
 * Календарь платформы просил выбрать день указателем — в поле, где человек
 * уже знает число с шильдика и быстрее его наберёт, чем пролистает год назад.
 * Формат при этом остаётся тем же, что у даты обнаружения утечки и что уходит
 * в книгу: точки ставит поле, а не набирающий, поэтому «12052020», «12.05.2020»
 * и «12/05/2020» дают одну и ту же строку.
 *
 * Ничего не достраивается и не проверяется на календарь: пока строка не
 * дописана, она возвращается как есть — иначе поле правило бы то, что человек
 * ещё набирает.
 *
 * @param {unknown} raw что стоит в поле после нажатия клавиши
 * @returns {string}
 */
export function maskDateInput(raw) {
  if (raw == null) return "";

  const digits = String(raw).replace(/\D/g, "").slice(0, 8);
  if (digits === "") return "";

  const parts = [digits.slice(0, 2), digits.slice(2, 4), digits.slice(4, 8)];
  return parts.filter((part) => part !== "").join(".");
}
