/**
 * Дата, записанная так, как её пишет человек: ДД.ММ.ГГГГ.
 *
 * Приложение хранит в этом виде дату импортированной записи, и в нём же её
 * набирают руками. Читателей у неё много — разбор книги, сведение архивов,
 * опознание записей обхода, показ на экране, — и каждый из них до сих пор
 * держал свою копию этого знания. Копии разошлись, и разошлись молча: `1` в
 * начале — это день, а `new Date` и `Date.parse` ждут месяц первым и от такой
 * строки не отказываются, а отдают другую дату. Числа больше двенадцатого за
 * месяц не сходят, и только на них всё случайно получалось верно.
 *
 * Поэтому знание здесь одно. Что делать с разобранными числами — дело
 * читателя: кому-то нужна `Date`, кому-то ключ для сравнения.
 *
 * Разделителем считается точка, косая черта или дефис: так дату пишут в разных
 * книгах, а порядок в ней от разделителя не меняется. Год из двух цифр
 * дополняется до двадцать первого века — записи прошлого столетия в обходе не
 * встречаются.
 *
 * ISO под шаблон не попадает: он начинается с четырёх цифр года, а здесь
 * первым стоит день из одной или двух.
 */
const HUMAN_DATE =
  /^(\d{1,2})[./-](\d{1,2})[./-](\d{2,4})(?:[ T](\d{1,2}):(\d{2}))?/;

/**
 * @param {unknown} value
 * @returns {{year: number, month: number, day: number, hours: number, minutes: number}|null}
 */
export function matchHumanDate(value) {
  const match = String(value ?? "")
    .trim()
    .match(HUMAN_DATE);
  if (!match) return null;

  const [, day, month, year, hours = "0", minutes = "0"] = match;
  return {
    year: year.length === 2 ? Number(`20${year}`) : Number(year),
    month: Number(month),
    day: Number(day),
    hours: Number(hours),
    minutes: Number(minutes),
  };
}
