/**
 * Глобальная область без `globalThis`.
 *
 * `globalThis` появился в Chrome 71, и тридцать четыре обращения держали на нём
 * пол поддержки. Это имя, а не синтаксис, — понизить его сборкой нельзя, на
 * старом WebView оно даёт `ReferenceError` при первом же обращении.
 *
 * `self` старше всего, что здесь нужно: в главном потоке это `window`, в
 * воркере — `WorkerGlobalScope`, в jsdom, где идут тесты, он тоже есть. Ветка
 * на `window` оставлена на случай окружения без `self`; ни одно из наших
 * четырёх такого не показывает, но обращение к глобальному имени, которого
 * может не быть, — ровно то, что здесь чинится.
 */
export const globalScope = typeof self === "undefined" ? window : self;
