/**
 * Классификация чанков по имени — та часть бюджета бандла, которая молчала.
 *
 * Проверка «ExcelJS остаётся ленивым» сравнивала шаблон с путями вида
 * `assets/<имя>`, а шаблон требовал границы слова перед `excel`: слева стоял
 * слэш, и совпадения не было никогда. `vendor-excel-*` проходил случайно — по
 * дефису. То есть страж, заведённый ровно на один сценарий, этот сценарий
 * пропустил бы, и никто бы не заметил: он ведь и не должен срабатывать.
 *
 * Вынесено из скрипта отдельным модулем, потому что скрипт исполняет проверку
 * на импорте и в тест его не втащить. Здесь — чистая функция.
 */

/**
 * Чанк самой библиотеки ExcelJS, а не всё, в чьём имени встретилось «excel».
 *
 * Имена вендорских чанков заданы явно: `vendor-excel` — группой в
 * `codeSplitting`, `exceljs.min` — копией, которую собирает воркер. Всё
 * остальное — код приложения: `excel-*.js` собирает `configs/shared/excel.js`
 * (обязательные колонки выгрузки), и в начальном графе он стоит законно;
 * `excel.worker-*.js` — сам воркер, он считается отдельно.
 *
 * @param {string} name имя файла или путь к нему
 * @returns {boolean}
 */
export function isExcelVendorChunk(name) {
  return /^(?:vendor-excel|exceljs)[-.]/i.test(
    String(name).replace(/^.*\//, ""),
  );
}
